import argparse
import glob
import json
import os
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent.parent.parent
DATASETS_DIR = PROJECT_ROOT / "datasets"
REPORTS_DIR = PROJECT_ROOT / "data" / "reports"


def get_file_size_mb(path: Path) -> float:
    try:
        return round(path.stat().st_size / (1024 * 1024), 2)
    except Exception:
        return 0.0


def profile_cic_ids2017():
    cic_dir = DATASETS_DIR / "CIC-IDS2017"
    if not cic_dir.exists():
        return {"status": "NOT FOUND", "files": []}
        
    csvs = list(cic_dir.glob("*.csv"))
    file_profiles = []
    total_size = sum(get_file_size_mb(f) for f in csvs)

    for f in csvs:
        try:
            with open(f, "r", encoding="utf-8", errors="replace") as fh:
                header = fh.readline().strip().split(",")
                row_count = sum(1 for _ in fh)
            file_profiles.append({
                "name": f.name,
                "size_mb": get_file_size_mb(f),
                "rows": row_count,
                "columns_count": len(header),
                "sample_columns": [c.strip() for c in header[:5]],
            })
        except Exception as e:
            file_profiles.append({"name": f.name, "error": str(e)})

    return {
        "status": "AVAILABLE",
        "total_files": len(csvs),
        "total_size_mb": round(total_size, 2),
        "files": file_profiles,
    }


